import json
import logging
from abc import ABC, abstractmethod
from typing import Dict, Any, List, Optional
import httpx

from backend.app.config import settings

logger = logging.getLogger("sentinel.ai")

class BaseAIProvider(ABC):
    @abstractmethod
    async def generate(
        self,
        prompt: str,
        system_instruction: str,
        conversation_history: Optional[List[Dict[str, str]]] = None
    ) -> Dict[str, Any]:
        """
        Returns a dict:
        {
            "content": str,
            "provider": str,
            "model": str,
            "tokens_used": int,
            "status": "success" | "quota_exhausted" | "unavailable" | "disabled",
            "message": Optional[str]
        }
        """
        pass

    @abstractmethod
    def health_check(self) -> Dict[str, Any]:
        pass

class GeminiFreeProvider(BaseAIProvider):
    """
    Connects to the official Google Gemini API using an eligible Free Tier API key.
    Includes timeout, retry, and clear quota exhaustion handling.
    """
    def __init__(self, api_key: str, model: str = "gemini-1.5-flash"):
        self.api_key = api_key
        self.model = model
        self.endpoint = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model}:generateContent?key={self.api_key}"

    def health_check(self) -> Dict[str, Any]:
        if not self.api_key or self.api_key.startswith("your-"):
            return {"configured": False, "status": "NOT CONFIGURED", "model": self.model}
        return {"configured": True, "status": "AVAILABLE", "model": self.model, "provider": "gemini"}

    async def generate(
        self,
        prompt: str,
        system_instruction: str,
        conversation_history: Optional[List[Dict[str, str]]] = None
    ) -> Dict[str, Any]:
        if not self.api_key or self.api_key.startswith("your-"):
            return {
                "content": "AI provider (Gemini Free Tier) is not configured. Please configure GEMINI_API_KEY in your environment to enable AI analysis. Core Sentinel SOC functionality remains fully operational.",
                "provider": "gemini",
                "model": self.model,
                "tokens_used": 0,
                "status": "disabled"
            }

        # Build contents array
        contents = []
        if conversation_history:
            for item in conversation_history:
                role = "user" if item.get("role") == "user" else "model"
                contents.append({"role": role, "parts": [{"text": item.get("content", "")}]})
        contents.append({"role": "user", "parts": [{"text": prompt}]})

        payload = {
            "contents": contents,
            "systemInstruction": {
                "parts": [{"text": system_instruction}]
            },
            "generationConfig": {
                "temperature": 0.2,
                "maxOutputTokens": 2048
            }
        }

        try:
            async with httpx.AsyncClient(timeout=30.0) as client:
                res = await client.post(self.endpoint, json=payload)
                
                if res.status_code == 429:
                    logger.warning("Gemini API rate limit or quota exceeded.")
                    return {
                        "content": "AI quota temporarily unavailable. Core Sentinel SOC functionality is still operational.",
                        "provider": "gemini",
                        "model": self.model,
                        "tokens_used": 0,
                        "status": "quota_exhausted"
                    }
                
                if res.status_code != 200:
                    logger.error(f"Gemini API returned error: {res.status_code} - {res.text}")
                    return {
                        "content": f"AI service returned HTTP {res.status_code}. Core Sentinel SOC features remain active.",
                        "provider": "gemini",
                        "model": self.model,
                        "tokens_used": 0,
                        "status": "unavailable"
                    }
                
                data = res.json()
                text = ""
                candidates = data.get("candidates", [])
                if candidates and "content" in candidates[0]:
                    parts = candidates[0]["content"].get("parts", [])
                    text = "".join([p.get("text", "") for p in parts])
                
                usage = data.get("usageMetadata", {})
                total_tokens = usage.get("totalTokenCount", len(text.split()))

                return {
                    "content": text or "No response generated by model.",
                    "provider": "gemini",
                    "model": self.model,
                    "tokens_used": total_tokens,
                    "status": "success"
                }
        except httpx.TimeoutException:
            return {
                "content": "AI request timed out. Core Sentinel SOC monitoring remains operational.",
                "provider": "gemini",
                "model": self.model,
                "tokens_used": 0,
                "status": "unavailable"
            }
        except Exception as e:
            logger.error(f"Error calling Gemini: {e}")
            return {
                "content": f"AI temporarily unavailable: {str(e)}. Core Sentinel SOC functionality is unaffected.",
                "provider": "gemini",
                "model": self.model,
                "tokens_used": 0,
                "status": "unavailable"
            }

class LocalAIProvider(BaseAIProvider):
    """
    Connects to an optional local open-weights server (e.g., Ollama or vLLM).
    """
    def __init__(self, base_url: str, model: str = "llama3.2"):
        self.base_url = base_url.rstrip("/")
        self.model = model

    def health_check(self) -> Dict[str, Any]:
        return {"configured": True, "status": "LOCAL", "model": self.model, "provider": "local"}

    async def generate(
        self,
        prompt: str,
        system_instruction: str,
        conversation_history: Optional[List[Dict[str, str]]] = None
    ) -> Dict[str, Any]:
        messages = [{"role": "system", "content": system_instruction}]
        if conversation_history:
            for item in conversation_history:
                messages.append({"role": item.get("role", "user"), "content": item.get("content", "")})
        messages.append({"role": "user", "content": prompt})

        payload = {
            "model": self.model,
            "messages": messages,
            "temperature": 0.2
        }

        try:
            async with httpx.AsyncClient(timeout=45.0) as client:
                res = await client.post(f"{self.base_url}/chat/completions", json=payload)
                if res.status_code == 200:
                    data = res.json()
                    content = data["choices"][0]["message"]["content"]
                    tokens = data.get("usage", {}).get("total_tokens", len(content.split()))
                    return {
                        "content": content,
                        "provider": "local",
                        "model": self.model,
                        "tokens_used": tokens,
                        "status": "success"
                    }
                return {
                    "content": f"Local AI model returned status {res.status_code}. Sentinel SOC core features remain active.",
                    "provider": "local",
                    "model": self.model,
                    "tokens_used": 0,
                    "status": "unavailable"
                }
        except Exception as e:
            return {
                "content": f"Local AI model server unreachable at {self.base_url}. Sentinel SOC core monitoring remains fully active.",
                "provider": "local",
                "model": self.model,
                "tokens_used": 0,
                "status": "unavailable"
            }

class FallbackAIProvider(BaseAIProvider):
    """
    Intelligent built-in fallback when external AI is not configured.
    Provides deterministic security analysis and troubleshooting advice,
    guaranteeing Sentinel SOC never crashes or leaves users stranded.
    """
    def health_check(self) -> Dict[str, Any]:
        return {"configured": False, "status": "NOT CONFIGURED", "model": "rule-based-fallback", "provider": "fallback"}

    async def generate(
        self,
        prompt: str,
        system_instruction: str,
        conversation_history: Optional[List[Dict[str, str]]] = None
    ) -> Dict[str, Any]:
        content = (
            "**[Sentinel Automated Guidance]**\n\n"
            "An external Free-tier AI provider is not currently configured. "
            "Sentinel SOC operates using deterministic detection rules and local analytical models.\n\n"
            "- To enable full LLM conversational analysis, configure `GEMINI_API_KEY` or `LOCAL_AI_BASE_URL` in `.env`.\n"
            "- Core security telemetry, sensor ingestion, detection rules, alerts, and incident management remain 100% operational."
        )
        return {
            "content": content,
            "provider": "fallback",
            "model": "rule-based-engine",
            "tokens_used": 0,
            "status": "disabled"
        }

def get_ai_provider() -> BaseAIProvider:
    """
    Factory that returns the configured free-tier or local AI provider.
    """
    provider_type = (settings.AI_PROVIDER or "").lower().strip()
    
    if provider_type == "gemini" or (settings.GEMINI_API_KEY and not settings.GEMINI_API_KEY.startswith("your-")):
        if settings.GEMINI_API_KEY:
            return GeminiFreeProvider(api_key=settings.GEMINI_API_KEY, model=settings.GEMINI_MODEL)
            
    if provider_type == "local":
        return LocalAIProvider(base_url=settings.LOCAL_AI_BASE_URL, model=settings.LOCAL_AI_MODEL)
        
    return FallbackAIProvider()
